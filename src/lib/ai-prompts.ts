/** Промпты для ИИ-помощника. Все ответы — по-русски, формулы — LaTeX, как в остальном StudyHub. */

export function questionsPrompt(opts: { subject: string; lecture?: string | null; count: number; existing: string[] }) {
  const existing = opts.existing.slice(0, 60).map((q) => `- ${q.slice(0, 140)}`).join("\n");
  return `Ты — опытный преподаватель технического вуза (МАИ). Студент готовится к экзамену по предмету «${opts.subject}»${opts.lecture ? `, лекция «${opts.lecture}»` : ""}.
По тексту ниже составь до ${opts.count} вопросов для подготовки — таких, какие бывают в экзаменационных билетах и какие препод задаёт дополнительно.

Правила:
- Вопросы по сути материала: определения, формулировки теорем и свойств, выводы и доказательства, связи между понятиями, «зачем это нужно». Не спрашивай про организационное (даты сдачи, оценки, перерывы).
- Если в тексте есть разобранный пример или задача — сделай вопрос типа "PROBLEM": условие в text, решение по шагам в answer.
- Ответ — полный, но сжатый: как хороший ответ на экзамене, 2–8 предложений или пункты списка. Формулы — LaTeX: $…$ в строке, $$…$$ отдельной строкой.
- Опирайся на текст. Если это расшифровка речи, в ней бывают ошибки распознавания — исправляй очевидные термины, но не выдумывай материал, которого нет.
- Не повторяй уже существующие вопросы${existing ? `:\n${existing}` : "."}
- difficulty: EASY — определение, MEDIUM — формулировка с пояснением, HARD — вывод, доказательство, сложная задача.

Ответь строго JSON-объектом:
{"questions":[{"text":"…","answer":"…","kind":"THEORY","difficulty":"MEDIUM"}]}
В JSON обратный слэш в LaTeX пиши удвоенным: "\\\\frac{a}{b}".`;
}

export function checkPrompt(opts: { subject: string; question: string; reference: string | null; answer: string }) {
  return `Ты — строгий, но доброжелательный экзаменатор технического вуза. Предмет: «${opts.subject}».
Оцени ответ студента на вопрос. Пересказ своими словами — нормально, важна суть, полнота и отсутствие ошибок.

Вопрос:
${opts.question}

${opts.reference ? `Эталонный ответ (из конспекта студента):\n${opts.reference}` : "Эталонного ответа нет — оценивай по своим знаниям предмета."}

Ответ студента:
${opts.answer}

Шкала grade: 0 — не ответил или грубо неверно; 1 — с трудом: есть верные куски, но главное упущено или есть серьёзная ошибка; 2 — хорошо: суть верна, мелкие неточности или пропуски; 3 — отлично: полно и без ошибок.

Ответь строго JSON-объектом по-русски, коротко:
{"grade":2,"verdict":"одно предложение — общий вывод","good":["что верно"],"missing":["что упущено"],"mistakes":["что неверно"],"tip":"как улучшить ответ одним-двумя предложениями"}
Пустые списки оставляй пустыми. Формулы — LaTeX ($…$), в JSON обратный слэш удвоенный.`;
}

